"""Second question types for hand-written frameworks.

Each module in scripts/second_specs/ defines FILE (problems file stem) and ADD, a list of
(objective code, Q(...)) pairs written with the opl DSL. This script writes drills/problems/<FILE>.yaml
and adds each template's name to the `drills:` list of its objective in the framework file (found by the
code's prefix), leaving everything else on the line alone. Re-running is idempotent. Frameworks generated
by scripts/opl_fill.py take their second types in their own spec instead (see ms.py's SECOND).
"""
import glob, importlib.util, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from opl_dsl import Q  # noqa: E402,F401

FWFILE = {}
for f in glob.glob(os.path.join(ROOT, "drills/frameworks/*.yaml")):
    t = open(f).read()
    m = re.search(r"^code: *(\S+)", t, re.M)
    if m: FWFILE.setdefault(m.group(1), []).append(f)


def add_drill(path, code, name):
    unit_n = topic_n = None
    lines = open(path).read().split("\n")
    _, rest = code.split("-", 1)
    u, t, lo = rest.split(".")
    for i, ln in enumerate(lines):
        m = re.match(r"^    n: (\d+)", ln)
        if m: unit_n, topic_n = m.group(1), None
        m = re.match(r"^      - n: (\d+)", ln)
        if m: topic_n = m.group(1)
        if unit_n == u and topic_n == t and re.match(rf"^\s+- \{{ id: {re.escape(lo)},", ln):
            m = re.search(r"drills: \[([^\]]*)\]", ln)
            if not m: sys.exit(f"{code}: no drills list on its line")
            have = [x.strip() for x in m.group(1).split(",") if x.strip()]
            if name not in have:
                have.append(name)
                lines[i] = ln[:m.start()] + f"drills: [{', '.join(have)}]" + ln[m.end():]
                open(path, "w").write("\n".join(lines))
            return
    sys.exit(f"{code}: objective not found in {path}")


total = 0
for spec in sorted(glob.glob(os.path.join(ROOT, "scripts/second_specs/*.py"))):
    name = os.path.basename(spec)[:-3]
    sp = importlib.util.spec_from_file_location(name, spec); mod = importlib.util.module_from_spec(sp)
    sys.modules[name] = mod; sp.loader.exec_module(mod)
    head = f"# Generated by scripts/second_types.py from scripts/second_specs/{name}.py: edit the spec, not this file.\n# Second question types; keys recomputed by sympy along another route.\n\n"
    body = yaml.safe_dump([q.to_yaml() for _, q in mod.ADD], allow_unicode=True, sort_keys=False, width=10000, default_flow_style=False)
    open(os.path.join(ROOT, f"drills/problems/{mod.FILE}.yaml"), "w").write(head + body)
    for code, q in mod.ADD:
        files = FWFILE.get(code.split("-")[0], [])
        fw = [f for f in files if os.path.basename(f)[:-5] == getattr(mod, "FRAMEWORK", "")] or files
        if len(fw) != 1: sys.exit(f"{code}: framework code is ambiguous or unknown {fw}; set FRAMEWORK in {name}.py")
        add_drill(fw[0], code, q.name)
        total += 1
print(f"second types: {total} templates")
