// Keeps the `wiki:` links in drills/sources/*.yaml honest.
//
//   node scripts/check-wiki.mjs                 check every link against drills/wiki-pages.json; exit 1 on a dead one
//   node scripts/check-wiki.mjs --wiki <dir>    first refresh drills/wiki-pages.json from a checkout of the wiki repo
//
// The wiki is a separate (private) repo, so the check runs against a snapshot: for every textbook
// folder a source points into, the list of its pages and which of them hold a drill zone. Refresh
// the snapshot whenever wiki pages are added, renamed or removed.
//
// Also writes docs/coverage/wiki-links.md: what is linked, which book sections have no wiki page,
// and which wiki drill pages no section points at.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import yaml from "js-yaml";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const snapshotFile = path.join(root, "drills/wiki-pages.json");
const args = process.argv.slice(2);
const wikiDir = args.includes("--wiki") ? args[args.indexOf("--wiki") + 1] : null;

// ── every wiki link the sources make ────────────────────────────────────────
const sources = fs
  .readdirSync(path.join(root, "drills/sources"))
  .filter((f) => f.endsWith(".yaml"))
  .sort()
  .map((f) => yaml.load(fs.readFileSync(path.join(root, "drills/sources", f), "utf8")));
const links = []; // { source, where, path }
const sectionsWithout = {}; // source id -> ["§1.4 Title", …] sections that teach a skill but have no page of their own
for (const s of sources) {
  if (s.wiki) links.push({ source: s.id, where: "book", path: s.wiki });
  sectionsWithout[s.id] = [];
  for (const ch of s.chapters ?? []) {
    if (ch.wiki) links.push({ source: s.id, where: `Ch ${ch.n}`, path: ch.wiki });
    for (const sec of ch.sections ?? []) {
      if (sec.wiki) links.push({ source: s.id, where: `§${sec.ref}`, path: sec.wiki });
      else if ((sec.skills ?? []).length) sectionsWithout[s.id].push(`§${sec.ref}${sec.title ? ` ${sec.title}` : ""}`);
    }
  }
}
const folderOf = (p) => p.split("/").slice(0, 2).join("/"); // textbooks/<slug>

// ── refresh the snapshot from a wiki checkout ───────────────────────────────
if (wikiDir) {
  const content = path.join(wikiDir, "content");
  if (!fs.existsSync(content)) {
    console.error(`${wikiDir} has no content/ folder; is it the wiki repo?`);
    process.exit(1);
  }
  const folders = [...new Set(links.map((l) => folderOf(l.path)))].sort();
  const snap = { folders: {} };
  for (const folder of folders) {
    const dir = path.join(content, folder);
    if (!fs.existsSync(dir)) {
      snap.folders[folder] = null; // the folder itself is gone
      continue;
    }
    const pages = {};
    const walk = (d) => {
      for (const e of fs.readdirSync(d, { withFileTypes: true })) {
        const full = path.join(d, e.name);
        if (e.isDirectory()) walk(full);
        else if (e.name.endsWith(".md")) {
          const rel = path.relative(content, full).replace(/\\/g, "/").replace(/\.md$/, "").replace(/\/index$/, "");
          const text = fs.readFileSync(full, "utf8");
          const title = /^title:\s*["']?(.+?)["']?\s*$/m.exec(text)?.[1] ?? "";
          pages[rel] = { title, drill: text.includes("tp-drill-zone") };
        }
      }
    };
    walk(dir);
    snap.folders[folder] = Object.fromEntries(Object.entries(pages).sort(([a], [b]) => a.localeCompare(b)));
  }
  fs.writeFileSync(snapshotFile, JSON.stringify(snap, null, 1) + "\n");
  console.log(`drills/wiki-pages.json: ${folders.length} textbook folders, ${Object.values(snap.folders).reduce((n, p) => n + Object.keys(p ?? {}).length, 0)} pages`);
}

// ── check ───────────────────────────────────────────────────────────────────
if (!fs.existsSync(snapshotFile)) {
  console.error("drills/wiki-pages.json is missing. Run: node scripts/check-wiki.mjs --wiki <path to the wiki repo>");
  process.exit(1);
}
const snap = JSON.parse(fs.readFileSync(snapshotFile, "utf8"));
const dead = [];
const unknownFolder = new Set();
for (const l of links) {
  const folder = folderOf(l.path);
  if (!(folder in snap.folders)) unknownFolder.add(folder);
  else if (!snap.folders[folder] || !(l.path in snap.folders[folder])) dead.push(l);
}

// ── report ──────────────────────────────────────────────────────────────────
const linked = new Set(links.map((l) => l.path));
let md = `# Wiki links\n\nGenerated by \`scripts/check-wiki.mjs\` from \`drills/sources/*.yaml\` and \`drills/wiki-pages.json\`.\n\n`;
md += `| Source | Wiki folder | Links | Dead | Sections with drills but no page | Wiki drill pages nothing points at |\n|---|---|---|---|---|---|\n`;
const detail = [];
for (const s of sources) {
  const mine = links.filter((l) => l.source === s.id);
  const folder = s.wiki ? folderOf(s.wiki) : null;
  const pages = folder ? snap.folders[folder] : null;
  const orphans = pages ? Object.entries(pages).filter(([p, v]) => v.drill && !linked.has(p)).map(([p]) => p) : [];
  const deadHere = dead.filter((l) => l.source === s.id);
  md += `| ${s.id} | ${folder ? `\`${folder.split("/")[1]}\`` : "none"} | ${mine.length} | ${deadHere.length} | ${sectionsWithout[s.id].length} | ${orphans.length} |\n`;
  if (deadHere.length || sectionsWithout[s.id].length || orphans.length) {
    detail.push(`## ${s.id}\n`);
    if (deadHere.length) detail.push(`**Dead links**\n\n${deadHere.map((l) => `- ${l.where}: \`${l.path}\``).join("\n")}\n`);
    if (sectionsWithout[s.id].length) detail.push(`**Sections that teach a skill but have no wiki page**\n\n${sectionsWithout[s.id].map((x) => `- ${x}`).join("\n")}\n`);
    if (orphans.length) detail.push(`**Wiki drill pages no section points at**\n\n${orphans.map((p) => `- \`${p}\`${pages[p].title ? ` — ${pages[p].title}` : ""}`).join("\n")}\n`);
  }
}
md += `\n${detail.join("\n")}`;
fs.mkdirSync(path.join(root, "docs/coverage"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/coverage/wiki-links.md"), md);

for (const f of unknownFolder) console.error(`not in the snapshot: ${f} (refresh with --wiki <path to the wiki repo>)`);
for (const l of dead) console.error(`dead wiki link: ${l.source} ${l.where} -> ${l.path}`);
console.log(`wiki links: ${links.length} from ${sources.length} sources, ${dead.length} dead, ${unknownFolder.size} folders not in the snapshot -> docs/coverage/wiki-links.md`);
if (dead.length || unknownFolder.size) process.exit(1);
