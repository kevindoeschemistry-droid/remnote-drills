// docs/frameworks/README.md: one table of every framework, what it is anchored on, and how much of it
// has drills. Runs last in `npm run skills`, reading the framework files and the standards registry.
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import yaml from "js-yaml";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const load = (f) => yaml.load(fs.readFileSync(f, "utf8"));
const standards = new Map((load(path.join(root, "drills/standards.yaml")) ?? []).map((s) => [s.id, s]));
const dir = path.join(root, "drills/frameworks");

const rows = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith(".yaml")).sort()) {
  const fw = load(path.join(dir, file));
  let los = 0, full = 0, partial = 0, types = 0;
  for (const u of fw.units ?? []) for (const t of u.topics ?? []) for (const lo of t.los ?? []) {
    los++;
    const ds = (lo.drills ?? []).map(String), whole = ds.filter((d) => !d.startsWith("~"));
    if (whole.length) { full++; types += ds.length; } else if (ds.length) partial++;
  }
  const b = standards.get(fw.basis?.primary);
  rows.push({ id: fw.id, title: fw.title, code: fw.code, track: fw.track ?? "other", los, full, partial, open: los - full - partial,
    per: full ? types / full : 0, basis: b ? `${b.name} (${b.kind}, read: ${b.read})` : (fw.basis?.primary ?? "none stated"), note: fw.basis?.note ?? "" });
}

const sum = (k) => rows.reduce((a, r) => a + r[k], 0);
const out = ["# Frameworks", "",
  "Generated by `npm run skills` (`scripts/framework-index.mjs`). One row per curriculum framework: what it is anchored on, how many objectives it has, and how many have drills. Click a framework for its objectives, the standard each one cites, and its drills.", "",
  `**${rows.length} frameworks · ${sum("los")} objectives · ${sum("full")} with drills · ${sum("partial")} partly · ${sum("open")} open.**`, "",
  "How to read the columns: *Drilled* means at least one drill covers the whole objective; *Partly* means only a drill marked as covering part of it; *Types* is the average number of different question types on a drilled objective (one type still varies its numbers every time, but it is one kind of question).", "",
  "Related reports: [standards and how much of each was read](../coverage/standards.md) · [variation grids](../coverage/matrices.md) · [the ordered path](PATH.md)", ""];
const tracks = [...new Set(rows.map((r) => r.track))].sort();
for (const tr of tracks) {
  out.push(`## ${tr[0].toUpperCase()}${tr.slice(1)}`, "", "| Framework | Code | Objectives | Drilled | Partly | Open | Types | Anchored on |", "|---|---|---:|---:|---:|---:|---:|---|");
  for (const r of rows.filter((x) => x.track === tr).sort((a, b) => b.full / (b.los || 1) - a.full / (a.los || 1) || a.title.localeCompare(b.title)))
    out.push(`| [${r.title}](${r.id}.md) | ${r.code} | ${r.los} | ${r.full} | ${r.partial} | ${r.open} | ${r.per ? r.per.toFixed(1) : "–"} | ${r.basis} |`);
  out.push("");
}
out.push("## What each basis does and does not cover", "");
for (const r of rows.sort((a, b) => a.title.localeCompare(b.title))) if (r.note) out.push(`- **${r.title}:** ${r.note}`);
fs.writeFileSync(path.join(root, "docs/frameworks/README.md"), out.join("\n") + "\n");
console.log(`framework index: ${rows.length} frameworks, ${sum("los")} objectives, ${sum("full")} drilled -> docs/frameworks/README.md`);
