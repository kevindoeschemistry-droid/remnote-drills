# look-alikes offered together in the name-the-structure items
GROUPS = [["glycine", "alanine", "valine", "leucine", "isoleucine"], ["serine", "threonine", "cysteine", "methionine"],
          ["aspartic acid", "glutamic acid", "asparagine", "glutamine"], ["lysine", "arginine", "proline", "histidine"],
          ["phenylalanine", "tyrosine", "tryptophan", "histidine"]]

HEAD = """# The 20 coded amino acids: draw each from its name, and name each from its drawing.
# GENERATED by scripts/mol.py --amino-acids from scripts/mol_amino.py: edit there, not here.
#
# Basis: IUPAC-IUB JCBN, Nomenclature and Symbolism for Amino Acids and Peptides (1983), 3AA-1,
# Table 1 (standards.yaml: iupac-aa-1983). Structures are the neutral forms that table prints.
# A draw item is self-graded: sketch it, reveal the structure, mark it yourself. Each structure's
# formula is recomputed from its atoms and bonds by tests/verify/molecules.py.
"""


def write(block):
    out = [HEAD]
    for name, three, one, smi, cond, hook in AA:
        slug = three.lower()
        out.append(f"""
- template: aa-draw-{slug}
  skill: biochem.amino-acids
  pace: quick
  prompt: 'Draw {name} ({three}, {one}) from memory: the neutral form, as a skeletal structure.'
  parts:
    - ask: 'Draw it on paper, then compare'
      label: a
      draw: true
      solution:
{block(smi, amino=True)}      explain: '{hook}. Condensed: ${cond}$'
""")
        group = next(g for g in GROUPS if name in g)
        if name == "histidine":
            group = GROUPS[4]
        opts = sorted(group if len(group) == 4 else ([name] + [g for g in group if g != name][:3] if name != "isoleucine" else ["isoleucine", "leucine", "valine", "alanine"]))
        if name == "glycine":
            opts = sorted(["glycine", "alanine", "serine", "valine"])
        out.append(f"""- template: aa-name-{slug}
  skill: biochem.amino-acids
  pace: recall
  prompt: 'Which amino acid is this?'
  figure:
{block(smi, amino=True, indent="    ")}  parts:
    - ask: 'Name it'
      label: a
      choice: [{", ".join(opts)}]
      correct: "{opts.index(name)}"
      explain: '{name[0].upper() + name[1:]} ({three}, {one}). {hook}'
  verify: {{ authored: true }}
""")
    path = Path(__file__).resolve().parents[1] / "drills/problems/bc-amino-acids.yaml"
    path.write_text("".join(out), encoding="utf8")
    print(f"wrote {path} ({len(AA)} amino acids)")
