"""Fill WeBWorK OPL gaps: specs in scripts/opl_specs/*.py → problems YAML, framework units, OPL map entries.

Each spec module defines FW (framework code), FILE (problems file stem), IDEA (a big-idea id of that
framework) and UNITS, a list of U(...). Running this script:
  - writes drills/problems/<FILE>.yaml from every template in the module;
  - writes the module's units into its framework between "# >>> opl-fill:<FILE>" markers (replaced on
    every run, so edit the spec, never the framework block);
  - adds each objective's code to the OPL sections it names in drills/standards/opl-map.yaml.
Then run `python3 scripts/opl_cite.py` and `npm run skills`.
"""
import glob, importlib.util, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from opl_dsl import Q, L, U  # noqa: E402


def q(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def unit_text(u, fw, idea):
    stds = sorted({f"webwork-opl:{s}" for _, los in u.topics for lo in los for s in lo.opl} | {s for _, los in u.topics for lo in los for s in lo.std})
    out = [f"  - id: {u.uid}", f"    n: {u.n}", f"    title: {q(u.title)}", "    scope: core",
           f"    std: [{', '.join(q(s) for s in (u.std or stds[:3]))}]", f"    ideas: [{idea}]", "    topics:"]
    for tn, (tt, los) in enumerate(u.topics, 1):
        out += [f"      - n: {tn}", f"        title: {q(tt)}", "        los:"]
        for lo in los:
            std = ", ".join([q(f"webwork-opl:{s}") for s in lo.opl] + [q(s) for s in lo.std])
            dr = ", ".join([x.name for x in lo.qs] + [d for d in lo.drills if d not in {x.name for x in lo.qs}])
            nd = f", needs: [{', '.join(lo.needs)}]" if lo.needs else ""
            out.append(f"          - {{ id: {lo.id}, std: [{std}], do: {q(lo.do)}, ek: [{q(lo.ek)}], p: [{lo.p}], drills: [{dr}]{nd} }}")
    return "\n".join(out)


FWFILE = {}
for f in glob.glob(os.path.join(ROOT, "drills/frameworks/*.yaml")):
    m = re.search(r"^code: *(\S+)", open(f).read(), re.M)
    if m: FWFILE[m.group(1)] = f

mapf = os.path.join(ROOT, "drills/standards/opl-map.yaml")
maptext = open(mapf).read()
total_q = total_lo = 0
for spec in sorted(glob.glob(os.path.join(ROOT, "scripts/opl_specs/*.py"))):
    name = os.path.basename(spec)[:-3]
    sp = importlib.util.spec_from_file_location(name, spec); mod = importlib.util.module_from_spec(sp)
    sys.modules[name] = mod; sp.loader.exec_module(mod)
    fwf = FWFILE[mod.FW]
    # problems
    qs = [x for u in mod.UNITS for _, los in u.topics for lo in los for x in lo.qs]
    names = [x.name for x in qs]
    dup = {n for n in names if names.count(n) > 1}
    if dup: sys.exit(f"{name}: duplicate template names {dup}")
    head = f"# Generated by scripts/opl_fill.py from scripts/opl_specs/{name}.py: edit the spec, not this file.\n# WeBWorK OPL gap-fill for framework {mod.FW}. One question each; keys recomputed by sympy along another route.\n\n"
    body = yaml.safe_dump([x.to_yaml() for x in qs], allow_unicode=True, sort_keys=False, width=10000, default_flow_style=False)
    open(os.path.join(ROOT, f"drills/problems/{mod.FILE}.yaml"), "w").write(head + body)
    # framework block
    s = open(fwf).read()
    block = f"  # >>> opl-fill:{mod.FILE} (generated by scripts/opl_fill.py; edit the spec)\n" + "\n".join(unit_text(u, mod.FW, mod.IDEA) for u in mod.UNITS) + f"\n  # <<< opl-fill:{mod.FILE}\n"
    pat = re.compile(rf"  # >>> opl-fill:{re.escape(mod.FILE)} .*?  # <<< opl-fill:{re.escape(mod.FILE)}\n", re.S)
    s = pat.sub(lambda _: block, s) if pat.search(s) else s.rstrip("\n") + "\n" + block
    open(fwf, "w").write(s)
    # map
    for u in mod.UNITS:
        for tn, (_, los) in enumerate(u.topics, 1):
            for lo in los:
                code = f"{mod.FW}-{u.n}.{tn}.{lo.id}"
                for sec in lo.opl:
                    m = re.search(rf"^{re.escape(sec)}: \[([^\]]*)\](.*)$", maptext, re.M)
                    if not m: sys.exit(f"{code}: no OPL section {sec} in the map")
                    have = [x.strip() for x in m.group(1).split(",") if x.strip()]
                    if code not in have: have.append(code)
                    maptext = maptext[:m.start()] + f"{sec}: [{', '.join(have)}]" + maptext[m.end():]
                total_lo += 1
    total_q += len(qs)
open(mapf, "w").write(maptext)
print(f"opl-fill: {total_lo} objectives, {total_q} templates")
