// Coverage report: for every full course (drills/courses/*.yaml), each lesson's skills and how
// many problem templates sit behind them.  GAP = no drill at all; THIN = fewer than 4 templates.
//   node scripts/coverage.mjs            -> docs/coverage/<course>.md for each course with units
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";

const here = path.dirname(fileURLToPath(import.meta.url));
const g = JSON.parse(fs.readFileSync(path.resolve(here, "../src/drills/skills.generated.json"), "utf8"));
const byId = Object.fromEntries(g.skills.map((s) => [s.id, s]));
const templates = (id) => new Set(Object.values(byId[id]?.levels ?? {}).flat()).size;
const outDir = path.resolve(here, "../docs/coverage");
fs.mkdirSync(outDir, { recursive: true });

for (const c of g.courses.filter((c) => c.units?.length)) {
  let lessons = 0, gaps = 0, thin = 0;
  const rows = [];
  for (const u of c.units) {
    rows.push(`\n## ${u.title}\n`, "| § | Lesson | Drills | Templates | Status |", "|---|---|---|---|---|");
    for (const l of u.lessons) {
      lessons++;
      const n = [...new Set(l.skills.flatMap((s) => Object.values(byId[s]?.levels ?? {}).flat()))].length;
      const status = !l.skills.length ? "**GAP**" : n < 4 ? "THIN" : "ok";
      if (status === "**GAP**") gaps++;
      else if (status === "THIN") thin++;
      rows.push(`| ${l.ref} | ${l.title} | ${l.skills.map((s) => byId[s]?.short ?? s).join(", ") || "—"} | ${n || "—"} | ${status} |`);
      if (l.note) rows.push(`| | ↳ ${l.note} | | | |`);
    }
  }
  const ms = (c.milestones ?? []).map((m) => `- **${m.name}** ${m.date}: units ${m.units.join(", ")}`).join("\n");
  const md = `# Coverage · ${c.title}\n\nGenerated by \`node scripts/coverage.mjs\`. ${lessons} lessons · ${gaps} gaps · ${thin} thin.\n\n${ms}\n${rows.join("\n")}\n`;
  fs.writeFileSync(path.join(outDir, `${c.id}.md`), md);
  console.log(`${c.id}: ${lessons} lessons, ${gaps} gaps, ${thin} thin -> docs/coverage/${c.id}.md`);
}
