#!/usr/bin/env python3
"""Periodic table recall: writes drills/problems/pt-periodic.yaml (plain Python).

Kevin's organometallics course expected the whole table from memory, the d and f blocks above all.
The table here is a flat list in order of atomic number; tests/verify/data.py holds its own copy laid
out by period and works groups out from position, so a slip in either one is caught by the other.
Group 3 below yttrium is left out of every question: IUPAC has not settled whether it is La or Lu.
"""
from pathlib import Path

NAMES = """hydrogen H, helium He, lithium Li, beryllium Be, boron B, carbon C, nitrogen N, oxygen O, fluorine F, neon Ne,
sodium Na, magnesium Mg, aluminium Al, silicon Si, phosphorus P, sulfur S, chlorine Cl, argon Ar, potassium K, calcium Ca,
scandium Sc, titanium Ti, vanadium V, chromium Cr, manganese Mn, iron Fe, cobalt Co, nickel Ni, copper Cu, zinc Zn,
gallium Ga, germanium Ge, arsenic As, selenium Se, bromine Br, krypton Kr, rubidium Rb, strontium Sr, yttrium Y, zirconium Zr,
niobium Nb, molybdenum Mo, technetium Tc, ruthenium Ru, rhodium Rh, palladium Pd, silver Ag, cadmium Cd, indium In, tin Sn,
antimony Sb, tellurium Te, iodine I, xenon Xe, caesium Cs, barium Ba, lanthanum La, cerium Ce, praseodymium Pr, neodymium Nd,
promethium Pm, samarium Sm, europium Eu, gadolinium Gd, terbium Tb, dysprosium Dy, holmium Ho, erbium Er, thulium Tm, ytterbium Yb,
lutetium Lu, hafnium Hf, tantalum Ta, tungsten W, rhenium Re, osmium Os, iridium Ir, platinum Pt, gold Au, mercury Hg,
thallium Tl, lead Pb, bismuth Bi, polonium Po, astatine At, radon Rn, francium Fr, radium Ra, actinium Ac, thorium Th,
protactinium Pa, uranium U, neptunium Np, plutonium Pu, americium Am, curium Cm, berkelium Bk, californium Cf, einsteinium Es, fermium Fm,
mendelevium Md, nobelium No, lawrencium Lr, rutherfordium Rf, dubnium Db, seaborgium Sg, bohrium Bh, hassium Hs, meitnerium Mt, darmstadtium Ds,
roentgenium Rg, copernicium Cn, nihonium Nh, flerovium Fl, moscovium Mc, livermorium Lv, tennessine Ts, oganesson Og"""
EL = [tuple(e.split()) for e in NAMES.replace("\n", " ").split(", ")]
assert len(EL) == 118
SYM = [s for _, s in EL]
Z = {s: i + 1 for i, s in enumerate(SYM)}


def dgroup(z):
    for lo, off in ((21, 18), (39, 36), (72, 68), (104, 100)):
        if lo <= z <= lo + 9 - (1 if lo in (72, 104) else 0):
            return z - off
    return None


DBLOCK = [z for z in range(1, 113) if dgroup(z)]
FBLOCK = list(range(57, 72)) + list(range(89, 104))
MAIN = [z for z in range(1, 119) if z not in DBLOCK and z not in FBLOCK]
row = lambda f: "    - { " + ", ".join(f"{a}: {b!r}" if isinstance(b, str) else f"{a}: {b}" for a, b in f.items()) + " }"
el = lambda z: {"nm": EL[z - 1][0], "sy": SYM[z - 1], "Zn": z}

out = ["""# Periodic table recall, d and f blocks first.
# GENERATED by scripts/pt_cases.py: edit there, not here.
# Basis: IUPAC Periodic Table of the Elements (release of 4 May 2022). Group 3 below yttrium is not asked.
"""]
for tag, zs, what in (("d-block", DBLOCK, "transition metal"), ("f-block", FBLOCK, "lanthanoid or actinoid"), ("main", MAIN, "main-group element")):
    out.append(f"""
- template: pt-number-{tag}
  skill: ptable.{'numbers' if tag == 'main' else tag}
  pace: recall
  cases:
{chr(10).join(row(el(z)) for z in zs)}
  prompt: 'What is the atomic number of {{{{nm}}}}, {{{{sy}}}}?'
  parts:
    - {{ ask: 'Atomic number', label: r, tex: 'Z', value: Zn, tol: 0.00001, explain: 'A {what}. Anchor on the ends of each row and count: the noble gases are 2, 10, 18, 36, 54, 86 and 118; the 3d row runs 21 to 30, the 4d row 39 to 48, the lanthanoids 57 to 71, the 5d row 72 to 80 and the actinoids 89 to 103' }}
  verify: {{ expect: {{ r: "pt_Z(sy)" }} }}
""")

out.append(f"""
- template: pt-group-d-block
  skill: ptable.d-block
  pace: recall
  cases:
{chr(10).join(row(el(z) | {"g": dgroup(z)}) for z in DBLOCK if z not in (21, 39))}
  prompt: 'Which group is {{{{nm}}}}, {{{{sy}}}}, in?'
  parts:
    - {{ ask: 'Group', label: r, tex: 'g', value: g, tol: 0.00001, explain: 'The group number of a transition metal is its count of valence electrons, s and d together, which is where every electron count in organometallic chemistry starts. Learn the columns as triads: Ti Zr Hf, V Nb Ta, Cr Mo W, Mn Tc Re, Fe Ru Os, Co Rh Ir, Ni Pd Pt, Cu Ag Au, Zn Cd Hg' }}
  verify: {{ expect: {{ r: "pt_group(pt_Z(sy))" }} }}
""")

below = [z for z in DBLOCK if 22 <= z <= 30 or 40 <= z <= 48]
out.append(f"""
- template: pt-congener-below
  skill: ptable.d-block
  pace: recall
  cases:
{chr(10).join(row(el(z) | {"zb": z + (18 if z <= 30 else 32), "sb": SYM[z + (18 if z <= 30 else 32) - 1], "nb": EL[z + (18 if z <= 30 else 32) - 1][0]}) for z in below)}
  prompt: 'What is the atomic number of the element directly below {{{{nm}}}}, {{{{sy}}}}?'
  parts:
    - {{ ask: 'Atomic number', label: r, tex: 'Z', value: zb, tol: 0.00001, explain: 'It is {{{{nb}}}}, {{{{sb}}}}. From the 3d row to the 4d row add 18. From the 4d row to the 5d row add 32, because the fourteen lanthanoids come in between; that is also why the 4d and 5d members of a triad are nearly the same size (the lanthanoid contraction)' }}
  verify: {{ expect: {{ r: "pt_below(pt_Z(sy))" }} }}
""")

IONS = """Ti 4, Ti 3, V 3, V 5, Cr 3, Cr 0, Cr 6, Mn 2, Mn 1, Mn 7, Fe 2, Fe 3, Fe 0, Co 3, Co 2, Co 1, Ni 2, Ni 0, Cu 1, Cu 2, Zn 2,
Zr 4, Nb 5, Mo 0, Mo 6, Mo 4, Ru 2, Ru 3, Rh 1, Rh 3, Pd 0, Pd 2, Ag 1, W 0, W 6, Re 1, Re 7, Os 8, Os 2, Ir 1, Ir 3, Pt 2, Pt 4, Pt 0, Au 1, Au 3, Hg 2"""
ROMAN = ["0", "I", "II", "III", "IV", "V", "VI", "VII", "VIII"]
ions = [(s, int(o)) for s, o in (e.split() for e in IONS.replace("\n", " ").split(", "))]
out.append(f"""
- template: pt-d-electron-count
  skill: ptable.d-block
  pace: recall
  cases:
{chr(10).join(row({"sy": s, "nm": EL[Z[s] - 1][0], "ox": o, "rom": ROMAN[o], "g": dgroup(Z[s]), "dn": dgroup(Z[s]) - o}) for s, o in ions)}
  prompt: 'What is the d-electron count of {{{{sy}}}}({{{{rom}}}})?'
  parts:
    - ask: 'd count'
      label: a
      choice: ["d0", "d1", "d2", "d3", "d4", "d5", "d6", "d7", "d8", "d9", "d10"]
      correct: dn
      explain: 'Group number minus oxidation state: {{{{nm}}}} is in group ${{{{g}}}}$, so ${{{{g}}}} - {{{{ox}}}} = {{{{dn}}}}$. In a complex all the valence electrons of the metal count as d electrons, whatever the configuration of the free atom'
  verify: {{ choices: {{ a: "pt_group(pt_Z(sy)) - ox" }} }}
""")

out.append(f"""
- template: pt-f-electron-count
  skill: ptable.f-block
  pace: recall
  cases:
{chr(10).join(row(el(z) | {"fn": z - 57}) for z in range(57, 72))}
  prompt: 'How many 4f electrons does the {{{{nm}}}} ion {{{{sy}}}}³⁺ have?'
  parts:
    - ask: '4f count'
      label: a
      choice: ["f0", "f1", "f2", "f3", "f4", "f5", "f6", "f7", "f8", "f9", "f10", "f11", "f12", "f13", "f14"]
      correct: fn
      explain: 'A Ln³⁺ ion has lost its 6s and 5d electrons, so what is left above the xenon core is all 4f: $Z - 3 - 54 = {{{{Zn}}}} - 57 = {{{{fn}}}}$. La³⁺ is f0, Gd³⁺ is the half-filled f7 and Lu³⁺ the filled f14'
  verify: {{ choices: {{ a: "pt_Z(sy) - 3 - pt_Z('Xe')" }} }}
""")

ROWS = [("3d", "the 3d row, scandium to zinc", range(21, 31)), ("4d", "the 4d row, yttrium to cadmium", range(39, 49)),
        ("5d", "the 5d row, hafnium to mercury", range(72, 81)), ("lanthanoids", "the lanthanoids, lanthanum to lutetium", range(57, 72)),
        ("actinoids", "the actinoids, actinium to lawrencium", range(89, 104)), ("6d", "the 6d row, rutherfordium to copernicium", range(104, 113)),
        ("p-block-heavy", "the sixth-period p block, thallium to radon", range(81, 87))]
for tag, what, zs in ROWS:
    zs = list(zs)
    out.append(f"""
- template: pt-write-{tag}
  skill: ptable.{'f-block' if 'oids' in tag else 'numbers' if 'p-block' in tag else 'd-block'}
  pace: quick
  prompt: 'From memory, write {what}: every symbol, in order, with the first and last atomic numbers.'
  parts:
    - ask: 'Write it on paper, then compare'
      label: a
      draw: true
      solution:
        type: table
        head: [{", ".join(repr(SYM[z - 1]) for z in zs)}]
        rows: [[{", ".join(str(z) for z in zs)}]]
      explain: 'Every symbol in the right order counts as a match; a swapped pair does not. If one stretch keeps slipping, say that stretch aloud as a run of three or four'
  verify: {{ authored: true }}
""")
triads = [[z, z + 18, z + 50] for z in range(22, 31)]
out.append(f"""
- template: pt-write-triad
  skill: ptable.d-block
  pace: recall
  cases:
{chr(10).join(row({"g": dgroup(t[0]), "s1": SYM[t[0] - 1], "s2": SYM[t[1] - 1], "s3": SYM[t[2] - 1], "z1": t[0], "z2": t[1], "z3": t[2]}) for t in triads)}
  prompt: 'From memory, write the three transition metals of group ${{{{g}}}}$, top to bottom, with their atomic numbers.'
  parts:
    - ask: 'Write it on paper, then compare'
      label: a
      draw: true
      solution:
        type: table
        head: ['{{{{s1}}}}', '{{{{s2}}}}', '{{{{s3}}}}']
        rows: [['{{{{z1}}}}', '{{{{z2}}}}', '{{{{z3}}}}']]
      explain: 'Down a group add 18, then 32. All three symbols and all three numbers must match'
  verify: {{ authored: true }}
""")
path = Path(__file__).resolve().parents[1] / "drills/problems/pt-periodic.yaml"
path.write_text("".join(out), encoding="utf8")
print("wrote", path)
