// The house standard against the outside ones.
//
//   drills/standards.yaml              outside standards (kind, how fully read, and their outline when cited item by item)
//   drills/frameworks/*.yaml  basis:   which standards a framework leans on (primary / also / wanted)
//                             std:     on a unit, topic or objective: outside items it answers to,
//                                      "fe-chemical:7.F"; a bare code ("K.CC.A.1") belongs to the primary
//
// Fails the build when a framework has no basis, or cites a standard or item that isn't in
// standards.yaml. Writes docs/coverage/standards.md: the basis of every framework, how much of
// each is anchored outside, and for each outlined standard which items nothing answers to yet.
//   node scripts/standards.mjs
import fs from "fs";
import path from "path";
import { fileURLToPath } from "url";
import yaml from "js-yaml";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const load = (f) => yaml.load(fs.readFileSync(path.join(root, f), "utf8"));
const standards = Object.fromEntries(load("drills/standards.yaml").map((s) => [s.id, s]));
const fwDir = path.join(root, "drills/frameworks");
const frameworks = fs.readdirSync(fwDir).filter((f) => f.endsWith(".yaml")).map((f) => load(`drills/frameworks/${f}`));
const errors = [];

// every citable item of an outlined standard: "7" and "7.F"
const items = {};
for (const s of Object.values(standards)) {
  if (!s.items) continue;
  items[s.id] = new Map();
  for (const it of s.items) {
    items[s.id].set(it.code, { title: it.title, weight: it.weight, area: true });
    for (const [k, t] of Object.entries(it.parts ?? {})) items[s.id].set(`${it.code}.${k}`, { title: t, parent: it.code });
  }
}

const KINDS = ["standard", "exam-spec", "course", "rubric", "rulebook", "textbook"];
const READS = ["full", "part", "crosswalk", "none"];
for (const s of Object.values(standards)) {
  if (!KINDS.includes(s.kind)) errors.push(`standards.yaml › ${s.id}: kind must be one of ${KINDS.join(", ")}`);
  if (!READS.includes(s.read)) errors.push(`standards.yaml › ${s.id}: read must be one of ${READS.join(", ")}`);
}

const arr = (x) => (x === undefined ? [] : [].concat(x));
const rows = []; // one per objective
const cited = {}; // standard -> item -> [{fw, code, drilled}]
for (const fw of frameworks) {
  const b = fw.basis;
  if (!b?.primary) { errors.push(`${fw.id}: needs a basis (basis.primary names a standard in drills/standards.yaml)`); continue; }
  for (const id of [b.primary, ...arr(b.also), ...arr(b.wanted)]) if (!standards[id]) errors.push(`${fw.id}: basis names unknown standard ${id}`);
  for (const u of fw.units ?? []) for (const t of u.topics ?? []) for (const lo of t.los ?? []) {
    const code = `${fw.code}-${u.n}.${t.n}.${lo.id}`;
    // heat transfer's older topic field: fe: [che-A] is the FE Chemical heat-transfer area, letter A
    const legacy = arr(t.fe).filter((x) => x.startsWith("che-")).map((x) => `fe-chemical:9.${x.slice(4)}`);
    const cites = [...arr(u.std), ...arr(t.std), ...arr(lo.std), ...legacy];
    const drilled = arr(lo.drills).some((d) => !d.startsWith("~"));
    let outside = false;
    for (const c of cites) {
      const i = c.indexOf(":");
      if (i < 0) { outside = true; continue; } // a bare code belongs to the primary standard
      const sid = c.slice(0, i), item = c.slice(i + 1);
      if (!standards[sid]) { errors.push(`${code}: cites unknown standard ${sid}`); continue; }
      if (items[sid] && !items[sid].has(item)) { errors.push(`${code}: ${sid} has no item ${item}`); continue; }
      outside = true;
      ((cited[sid] ??= {})[item] ??= []).push({ fw: fw.id, code, drilled });
    }
    rows.push({ fw: fw.id, code, outside, drilled });
  }
}
if (errors.length) { console.error(errors.map((e) => `standards: ${e}`).join("\n")); process.exit(1); }

// ── the report ───────────────────────────────────────────────────────────────
const name = (id) => standards[id].name;
const firm = { full: "read in full", part: "read in part", crosswalk: "read through a crosswalk", none: "not opened" };
let md = `# The house standard against outside standards\n\nGenerated by \`scripts/standards.mjs\`. Do not edit; change \`drills/standards.yaml\` or a framework's \`basis\` / \`std\`.\n\n`;
md += `Every objective has a house code (\`HT-2.2.A\`) that is ours. An objective is **anchored** when it, its topic or its unit cites an item of an outside standard, and **house only** when nothing outside asks for it yet.\n\n`;
md += `## Basis of each framework\n\n| Framework | Primary basis | Kind | How firmly | Also | Wanted | Objectives | Anchored | House only |\n|---|---|---|---|---|---|---|---|---|\n`;
for (const fw of frameworks) {
  const b = fw.basis, p = standards[b.primary], mine = rows.filter((r) => r.fw === fw.id);
  const anchored = mine.filter((r) => r.outside).length;
  md += `| ${fw.title} | ${p.name} | ${p.kind} | ${firm[p.read]} | ${arr(b.also).join(", ") || "—"} | ${arr(b.wanted).join(", ") || "—"} | ${mine.length} | ${anchored} | ${mine.length - anchored} |\n`;
}
const notes = frameworks.filter((f) => f.basis.note);
if (notes.length) md += `\n### Notes\n\n${notes.map((f) => `- **${f.title}**: ${f.basis.note}`).join("\n")}\n`;

const weak = frameworks.filter((f) => !["standard", "exam-spec"].includes(standards[f.basis.primary].kind) || standards[f.basis.primary].read !== "full");
md += `\n## Frameworks not yet on a fully read standard\n\n${weak.map((f) => `- **${f.title}**: ${standards[f.basis.primary].kind}, ${firm[standards[f.basis.primary].read]}${arr(f.basis.wanted).length ? `; should move to ${arr(f.basis.wanted).map(name).join("; ")}` : ""}`).join("\n")}\n`;

for (const [sid, map] of Object.entries(items)) {
  const s = standards[sid], hit = cited[sid] ?? {};
  const leaf = [...map.entries()].filter(([, v]) => !v.area);
  const covered = leaf.filter(([k, v]) => hit[k]?.length || hit[v.parent]?.length);
  md += `\n## ${s.name}\n\n${s.url ?? ""}\n\n${covered.length} of ${leaf.length} items have at least one objective answering to them.\n\n| Item | Topic | Objectives | With a drill | Where |\n|---|---|---|---|---|\n`;
  for (const [k, v] of map) {
    if (v.area) { md += `| **${k}** | **${v.title}** (${v.weight} questions) | | | |\n`; continue; }
    const h = hit[k] ?? [];
    const by = {};
    for (const x of h) by[x.fw] = (by[x.fw] ?? 0) + 1;
    md += `| ${k} | ${v.title} | ${h.length || "—"} | ${h.length ? h.filter((x) => x.drilled).length : "—"} | ${Object.entries(by).map(([f, n]) => `${f} (${n})`).join(", ") || "**nothing yet**"} |\n`;
  }
  const areas = [...map.entries()].filter(([, v]) => v.area).map(([k, v]) => ({ k, v, n: leaf.filter(([, x]) => x.parent === k).length, c: covered.filter(([, x]) => x.parent === k).length }));
  md += `\n**Areas with nothing answering to them:** ${areas.filter((a) => a.c === 0).map((a) => `${a.k} ${a.v.title}`).join("; ") || "none"}.\n`;
}
fs.mkdirSync(path.join(root, "docs/coverage"), { recursive: true });
fs.writeFileSync(path.join(root, "docs/coverage/standards.md"), md);
const anchoredAll = rows.filter((r) => r.outside).length;
console.log(`standards: ${frameworks.length} frameworks have a declared basis; ${anchoredAll} of ${rows.length} objectives anchored outside, ${rows.length - anchoredAll} house only; ${weak.length} frameworks not yet on a fully read standard -> docs/coverage/standards.md`);
