def opposite(cells, q):
    # roll a die: keep the labels sitting on (bottom, top, north, south, east, west)
    pos = {q: dict(bottom="b", top="t", north="n", south="s", east="e", west="w")}
    todo = [q]
    while todo:
        i = todo.pop()
        o = pos[i]
        for j, (x, y) in enumerate(cells):
            if j in pos:
                continue
            dx, dy = x - cells[i][0], y - cells[i][1]
            if dx == 1 and dy == 0: n = dict(bottom=o["east"], top=o["west"], east=o["top"], west=o["bottom"], north=o["north"], south=o["south"])
            elif dx == -1 and dy == 0: n = dict(bottom=o["west"], top=o["east"], west=o["top"], east=o["bottom"], north=o["north"], south=o["south"])
            elif dy == 1 and dx == 0: n = dict(bottom=o["north"], top=o["south"], north=o["top"], south=o["bottom"], east=o["east"], west=o["west"])
            elif dy == -1 and dx == 0: n = dict(bottom=o["south"], top=o["north"], south=o["top"], north=o["bottom"], east=o["east"], west=o["west"])
            else: continue
            pos[j] = n
            todo.append(j)
    return next(j for j, o in pos.items() if o["bottom"] == "t")


