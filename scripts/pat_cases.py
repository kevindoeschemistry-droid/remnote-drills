DEPTHS = [2, 1, 3, 2, 1, 3, 2, 3, 1, 3, 2, 1]


def pcode(P):
    return int("1" + "".join("%x" % (4 * x + z) for x, z in P), 16)


def canon(P):
    """a polygon up to shifting, starting corner and direction"""
    mx, my = min(x for x, y in P), min(y for x, y in P)
    Q = [(x - mx, y - my) for x, y in P]
    n = len(Q)
    return min(tuple(seq[i:] + seq[:i]) for seq in (Q, Q[::-1]) for i in range(n))


def turned(P):
    return {canon([((y if sw else x) * sx, (x if sw else y) * sy) for x, y in P]) for sx, sy, sw in itertools.product((1, -1), (1, -1), (0, 1))}


def rect(w, h):
    return [(0, 0), (w, 0), (w, h), (0, h)]


def reach(P, axis, at):
    """furthest point of the profile along `axis` on the grid line where the other coordinate is `at`"""
    best = None
    for i in range(len(P)):
        p, q = P[i], P[(i + 1) % len(P)]
        a, c = p[1 - axis], q[1 - axis]
        if a == at and c == at:
            cand = max(p[axis], q[axis])
        elif a != c and min(a, c) <= at <= max(a, c):
            cand = p[axis] + Fr((q[axis] - p[axis]) * (at - a), c - a)
        else:
            continue
        best = cand if best is None or cand > best else best
    return best


def pview(P, D, which):
    """what a view of the prism looks like, in a form two views can be compared by"""
    xs, zs = [x for x, z in P], [z for x, z in P]
    W, Hh = max(xs) - min(xs), max(zs) - min(zs)
    if which == 1:
        c = canon(P)
        return ("rect", W, Hh, (), ()) if c == canon(rect(W, Hh)) else ("poly", c)
    if which == 0:
        lines = tuple(sorted((x - min(xs), 1 if (x, reach(P, 1, x)) in P else 2) for x in set(xs) if min(xs) < x < max(xs)))
        return ("rect", W, D, lines, ())
    lines = tuple(sorted((max(zs) - z, 1 if (reach(P, 0, z), z) in P else 2) for z in set(zs) if min(zs) < z < max(zs)))
    return ("rect", D, Hh, (), lines)


