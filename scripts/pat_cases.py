def voxels(h):  # (x, y, z): x = column, y = distance from the front, z = height
    R = len(h)
    return {(c, R - 1 - r, z) for r in range(R) for c in range(len(h[0])) for z in range(h[r][c])}


def project(h, which):
    """(solid, dashed) segments of a view from crease edges. View axes (u right, v down, d away from the eye)."""
    V = voxels(h)
    R, C, top = len(h), len(h[0]), max(max(r) for r in h)
    if which == 0:   # top: u = x, v grows toward the front, depth = top - z
        to = lambda x, y, z: (x, R - y, top - z)
    elif which == 1:  # front: u = x, v = top - z, depth = y
        to = lambda x, y, z: (x, top - z, y)
    else:             # end (from the right): u = y, v = top - z, depth = C - x
        to = lambda x, y, z: (y, top - z, C - x)
    cellfront = {}
    for (x, y, z) in V:   # nearest occupied depth of each projected square
        corners = [to(x + a, y + b, z + c) for a in (0, 1) for b in (0, 1) for c in (0, 1)]
        u, v, d = min(p[0] for p in corners), min(p[1] for p in corners), min(p[2] for p in corners)
        cellfront[(u, v)] = min(cellfront.get((u, v), 99), d)
    solid, dash = set(), set()
    for ax in range(3):
        o1, o2 = [a for a in range(3) if a != ax]
        for x in range(C + 1):
            for y in range(R + 1):
                for z in range(top + 1):
                    base = (x, y, z)
                    if base[ax] >= (C, R, top)[ax]:
                        continue
                    around = []
                    for da in (-1, 0):
                        for db in (-1, 0):
                            q = list(base); q[o1] += da; q[o2] += db
                            around.append(tuple(q) in V)
                    n = sum(around)
                    if n in (0, 4) or (n == 2 and around[0] != around[3]):
                        continue  # nothing there, buried, or the middle of a flat face
                    end = list(base); end[ax] += 1
                    p, q = to(*base), to(*end)
                    if (p[0], p[1]) == (q[0], q[1]):
                        continue  # runs along the line of sight: seen as a point
                    seg = (min(p[0], q[0]), min(p[1], q[1]), max(p[0], q[0]), max(p[1], q[1]))
                    depth = p[2]
                    sides = [(seg[0], seg[1] - 1), (seg[0], seg[1])] if seg[1] == seg[3] else [(seg[0] - 1, seg[1]), (seg[0], seg[1])]
                    hidden = all(cellfront.get(sq, 99) < depth for sq in sides)
                    (dash if hidden else solid).add(seg)
    dash -= solid
    pts = [(a, b) for g in (solid, dash) for (x1, y1, x2, y2) in g for (a, b) in ((x1, y1), (x2, y2))]
    mx, my = min(p[0] for p in pts), min(p[1] for p in pts)
    sh = lambda g: frozenset((x1 - mx, y1 - my, x2 - mx, y2 - my) for (x1, y1, x2, y2) in g)
    return sh(solid), sh(dash)


def shadow(h, which):
    """silhouette as a set of unit squares"""
    R, C = len(h), len(h[0])
    if which == 0:
        return {(c, r) for r in range(R) for c in range(C) if h[r][c]}
    if which == 1:
        return {(c, -z) for r in range(R) for c in range(C) for z in range(h[r][c])}
    return {(R - 1 - r, -z) for r in range(R) for c in range(C) for z in range(h[r][c])}


def norm(cells):
    mx, my = min(x for x, y in cells), min(y for x, y in cells)
    return frozenset((x - mx, y - my) for x, y in cells)


def congruent(cells):
    res = set()
    for sx, sy, swap in itertools.product((1, -1), (1, -1), (0, 1)):
        res.add(norm({((y if swap else x) * sx, (x if swap else y) * sy) for x, y in cells}))
    return res


def hfields(h, pre):
    return {f"{pre}{r+1}{c+1}": h[r][c] for r in range(3) for c in range(3)}


def row(f):
    return "    - { " + ", ".join(f"{a}: {b}" for a, b in f.items()) + " }"


