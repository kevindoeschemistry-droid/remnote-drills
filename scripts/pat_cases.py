def pack(g):
    return int("1" + "".join(str(v) for r in g for v in r))


def consistent(h, given):
    """every 3 x 3 stack (heights 0..3) whose `given` views are drawn exactly like those of h"""
    top = max(max(r) for r in h)
    want = {k: project(h, k) for k in given}
    shade = {k: norm(shadow(h, k)) for k in given}
    rowmax, colmax = [max(r) for r in h], [max(h[r][c] for r in range(3)) for c in range(3)]
    cap = [[min((colmax[c] if 1 in given else 3), (rowmax[r] if 2 in given else 3), (3 if 0 not in given or h[r][c] else 0)) for c in range(3)] for r in range(3)]
    found = []
    for flat in itertools.product(*[range((1 if 0 in given and h[r][c] else 0), cap[r][c] + 1) for r in range(3) for c in range(3)]):
        g = [list(flat[0:3]), list(flat[3:6]), list(flat[6:9])]
        if max(flat) != top or any(norm(shadow(g, k)) != shade[k] for k in given):
            continue
        if all(project(g, k) == want[k] for k in given):
            found.append(g)
    return found


def lettered(right, wrong):
    """shuffle one right answer among three wrong ones; returns (options, index of the right one)"""
    opts = [right] + wrong
    order = list(range(4)); rnd.shuffle(order)
    return [opts[i] for i in order], order.index(0)


