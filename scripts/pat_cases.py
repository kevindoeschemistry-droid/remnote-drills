def unfold(folds, p):
    holes = {p}
    for axis, line, side in reversed(folds):
        new = set(holes)
        for h in holes:
            v = 2 * line - h[axis]
            # the mirrored point belongs to the part that was folded over, if it lies on the sheet
            if 0 < v < 4 and (v - line) * side > 0:
                new.add((v, h[1]) if axis == 0 else (h[0], v))
        holes = new
    return holes


