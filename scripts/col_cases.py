"""Colloids and DLVO theory → drills/problems/mt-colloids.yaml (framework materials, unit 3).

Closed forms go straight into the templates; the DLVO barrier needs a root, so its cases are
computed here by Newton's method on the analytic derivative and stored in the cases. The verifier
(tests/verify/colcalc.py) recomputes everything along other routes: Debye lengths from ion lists,
sphere energies by integrating plate energies through Derjaguin, the barrier by bisection on a
numerical slope.

    python3 scripts/col_cases.py
"""
import mpmath as mp
from pathlib import Path

mp.mp.dps = 30
E, KB, NA = mp.mpf("1.602176634e-19"), mp.mpf("1.380649e-23"), mp.mpf("6.02214076e23")
EPS0, EPSR, T = mp.mpf("8.8541878128e-12"), mp.mpf("78.4"), mp.mpf("298.15")
KT = KB * T
OUT = Path(__file__).resolve().parent.parent / "drills/problems/mt-colloids.yaml"

# the constants as the cards and mathjs values write them
EPS = "78.4*8.8541878128e-12"
kT = "1.380649e-23*298.15"
DEBYE = f"sqrt({EPS}*{kT}/(2*6.02214076e23*1.602176634e-19^2*I))"  # m, I in mol/m³ (= mM)


def barrier(R_nm, A, psi_mV, I_mM):
    R, psi = mp.mpf(R_nm) * 1e-9, mp.mpf(psi_mV) / 1000
    kappa = mp.sqrt(2 * NA * E**2 * mp.mpf(I_mM) / (EPSR * EPS0 * KT))
    W = lambda D: 2 * mp.pi * EPSR * EPS0 * R * psi**2 * mp.e ** (-kappa * D) - A * R / (12 * D)
    dW = lambda D: -2 * mp.pi * EPSR * EPS0 * R * psi**2 * kappa * mp.e ** (-kappa * D) + A * R / (12 * D**2)
    # walk out from contact until the slope turns negative, then solve inside that bracket
    lo = 1 / kappa / 1000
    while dW(lo * 1.05) > 0:
        lo *= 1.05
        if lo > 20 / kappa:
            raise ValueError("no barrier")
    D = mp.findroot(dW, (lo, lo * 1.05), solver="anderson")
    return W(D) / KT, D * 1e9


def barrier_cases():
    rows = []
    for R in (50, 100, 200):
        for psi in (30, 40, 50):
            for I in (1, 10, 50, 100, 200):
                h, D = barrier(R, mp.mpf("1e-20"), psi, I)
                if h > 1:
                    rows.append(f"    - {{ R: {R}, psi: {psi}, I: {I}, ions: '{I}:1,{I}:1', h: {mp.nstr(h, 15)} }}")
    return "\n".join(rows)


